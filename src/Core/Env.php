<?php
declare(strict_types=1);

namespace SmartCanteen\Core;

/** Minimal .env loader. Real environment variables win over the file. */
final class Env
{
    /** @var array<string,string> */
    private static array $values = [];

    public static function load(string $file): void
    {
        if (!is_file($file)) {
            return;
        }
        foreach (file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
            $line = trim($line);
            if ($line === '' || $line[0] === '#' || !str_contains($line, '=')) {
                continue;
            }
            [$key, $val] = explode('=', $line, 2);
            $key = trim($key);
            $val = trim($val);
            if (strlen($val) >= 2 && ($val[0] === '"' || $val[0] === "'") && $val[0] === substr($val, -1)) {
                $val = substr($val, 1, -1);
            } else {
                // unquoted value: drop a trailing "  # comment"
                $val = trim(preg_replace('/\s+#.*$/', '', $val));
            }
            self::$values[$key] = $val;
        }
    }

    public static function get(string $key, ?string $default = null): ?string
    {
        $env = getenv($key);
        if ($env !== false && $env !== '') {
            return $env;
        }
        return self::$values[$key] ?? $default;
    }

    public static function bool(string $key, bool $default = false): bool
    {
        $v = self::get($key);
        return $v === null ? $default : in_array(strtolower($v), ['1', 'true', 'yes', 'on'], true);
    }
}
